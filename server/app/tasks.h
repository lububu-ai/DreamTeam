#ifndef TASKS_H
#define TASKS_H

#include <QString>
#include <QStringList>
#include <functional>
#include <vector>
#include <utility>
#include <cmath>
#include <algorithm>

/**
 * @file tasks.h
 * @brief Определение структуры задачи и функции её генерации.
 */

/**
 * @struct CurrentTask
 * @brief Структура для хранения информации о текущей задаче, выданной пользователю.
 */

struct CurrentTask {
    int type = 0; ///< Тип (номер) задачи от 1 до 5. Значение 0 означает отсутствие задачи.
    QString payload = ""; ///< Исходные параметры задачи (строка с разделителями для отправки клиенту).
    QString answer = ""; ///< Правильный ответ на задачу для проверки серверной частью.
    /**
     * @brief Проверяет, валидна (задана) ли текущая задача.
     * @return true, если тип не равен 0.
     */
    bool is_valid() const;
    /**
     * @brief Сбрасывает поля структуры в значения по умолчанию.
     */
    void clear();
};

/**
 * @brief Генератор случайных задач по типам.
 * * Поддерживает 5 различных математических/алгоритмических задач:
 * - 1: Формула Симпсона (Мусихин)
 * - 2: Метод хорд / Линейные функции (Филатов)
 * - 3: Дихотомия / деление отрезка (Шилова)
 * - 4: Поиск листьев в дереве обходом в глубину (Семенец)
 * - 5: Вычисление аналитической функции с логарифмом и корнем (Рыбакин)
 * * @param task_type Идентификатор типа задачи (1..5).
 * @return CurrentTask Заполненный объект сгенерированной задачи.
 */
CurrentTask generate_task(int task_type);

#endif // TASKS_H
